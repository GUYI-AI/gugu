#!/usr/bin/env python3
"""Derive theme PNGs from the bundled Pi image; no imaging dependency required."""
from pathlib import Path
import argparse
import base64
import hashlib
import struct
import zlib

ASSETS = Path(__file__).resolve().parents[1] / 'src/agents/impl/pi/assets'
SIGNATURE = b'\x89PNG\r\n\x1a\n'


def decode(data):
    if not data.startswith(SIGNATURE):
        raise ValueError('Not a PNG')
    offset, compressed = 8, bytearray()
    while offset < len(data):
        length = struct.unpack('>I', data[offset:offset + 4])[0]
        kind, payload = data[offset + 4:offset + 8], data[offset + 8:offset + 8 + length]
        if kind == b'IHDR':
            width, height, depth, color, compression, filtering, interlace = struct.unpack('>IIBBBBB', payload)
            if (depth, color, compression, filtering, interlace) != (8, 6, 0, 0, 0):
                raise ValueError('Expected non-interlaced RGBA8 original')
        if kind == b'IDAT':
            compressed.extend(payload)
        offset += length + 12
    raw, stride, rows, previous = zlib.decompress(compressed), width * 4, [], bytearray(width * 4)
    if len(raw) != height * (stride + 1):
        raise ValueError('Unexpected scanline length')
    for y in range(height):
        start = y * (stride + 1)
        mode, row = raw[start], bytearray(raw[start + 1:start + 1 + stride])
        for x in range(stride):
            left = row[x - 4] if x >= 4 else 0
            above, corner = previous[x], previous[x - 4] if x >= 4 else 0
            estimate = left + above - corner
            distances = (abs(estimate - left), abs(estimate - above), abs(estimate - corner))
            paeth = (left, above, corner)[distances.index(min(distances))]
            if mode > 4:
                raise ValueError('Invalid PNG filter')
            row[x] = (row[x] + (0, left, above, (left + above) // 2, paeth)[mode]) & 255
        rows.append(row)
        previous = row
    return width, height, b''.join(rows)


def chunk(kind, payload):
    return struct.pack('>I', len(payload)) + kind + payload + struct.pack('>I', zlib.crc32(kind + payload) & 0xffffffff)


def transparent(width, height, rgba, mark):
    corners = [rgba[i:i + 4] for i in [0, (width - 1) * 4, (height - 1) * width * 4, (width * height - 1) * 4]]
    if len(set(corners)) != 1 or corners[0][3] != 255:
        raise ValueError('Original background corners differ; review the source before converting')
    red, green, blue, _ = corners[0]
    black_point = (2126 * red + 7152 * green + 722 * blue + 5000) // 10000
    if black_point >= 255:
        raise ValueError('Expected a dark background')
    span = 255 - black_point
    pixels = bytearray()
    for offset in range(0, len(rgba), 4):
        red, green, blue, original_alpha = rgba[offset:offset + 4]
        luminance = (2126 * red + 7152 * green + 722 * blue + 5000) // 10000
        pixels.extend((mark, mark, mark, (max(0, luminance - black_point) * original_alpha + span // 2) // span))
    scanlines = b''.join(b'\0' + pixels[y * width * 4:(y + 1) * width * 4] for y in range(height))
    header = struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0)
    return SIGNATURE + chunk(b'IHDR', header) + chunk(b'IDAT', zlib.compress(scanlines, 9)) + chunk(b'IEND', b'')


def outputs():
    source = (ASSETS / 'pi-original.png').read_bytes()
    width, height, rgba = decode(source)
    light, dark = transparent(width, height, rgba, 0), transparent(width, height, rgba, 255)
    uri = lambda value: 'data:image/png;base64,' + base64.b64encode(value).decode('ascii')
    module = "import type { PluginIconAsset } from '@gugu/session-shared/plugins';\n\n"
    module += '// Generated by tooling/generate-pi-icons.py from assets/pi-original.png.\n'
    module += f'// Original SHA-256: {hashlib.sha256(source).hexdigest()}\n'
    module += "export const icon: PluginIconAsset = {\n  kind: 'image',\n  alt: 'Pi CLI',\n  variants: [{\n    minSize: 0,\n"
    module += f"    light: `{uri(light)}`,\n    dark: `{uri(dark)}`,\n  }}],\n}};\n"
    return {ASSETS / 'pi-light.png': light, ASSETS / 'pi-dark.png': dark, ASSETS.parent / 'icon.ts': module.encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, data in outputs().items():
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit(f'Generated Pi asset differs: {path.name}')
        else:
            path.write_bytes(data)
    print('Pi alpha assets match original-derived output' if args.check else 'Generated Pi alpha assets')


if __name__ == '__main__':
    main()
