import { COMMANDS, type CommandId, type MenuNamedCommandId } from '@shared/commands';

/**
 * The built-in commands' shown words (shortcut settings, cheat sheet, command palette).
 * English stays in the command catalog (`shared/commands.ts`) and is read from there; a command named by a menu's own
 * entry (`labelKey`) keeps that one name, so only the others get a `command.<id>` name here. Every command has help text.
 */
type CatalogNamedCommandId = Exclude<CommandId, MenuNamedCommandId>;
type CommandCopyKey = `command.${CatalogNamedCommandId}` | `commandHelp.${CommandId}`;

export const enUSCommandMessages = Object.fromEntries(
  Object.entries(COMMANDS).flatMap(([id, def]) => [
    ...(def.labelKey ? [] : [[`command.${id}`, def.label] as const]),
    [`commandHelp.${id}`, def.description] as const,
  ]),
) as Record<CommandCopyKey, string>;

